#!/usr/bin/env bash
# Emit a state-mate `<net>.deployed.yaml` sibling from this migration's freshly-deployed addresses.
#
# Usage: write-deployed-yaml.sh OUT_PATH POOL TRIGGER RECEIVER
#   env DEPLOYED_YAML_GENERATOR — the recipe named in the generated header (default "just deploy-test").
#   `just deploy-automation` sets it, because a pair-only redeploy produces this file too and the header
#   must name the recipe that actually wrote it rather than the one that first created the lane.
#
# The three addresses are the ONLY contracts this migration deploys (OraclePool, SyncTrigger,
# CREReceiver) — so this file is always regenerable from a deploy broadcast, with no pre-existing
# seed. The pre-existing CustomSender proxy/impl + ProxyAdmin are NOT here: they are fixed external
# facts pinned in config/state/l2-<net>.inputs.yaml (externals:), cross-checked by verify-constants-sync.
# Every value is validated as a non-zero 0x+40hex address and checksummed before writing — the
# state-mate `.deployed` loader rejects `null`/placeholder, so we fail early here with a clear message.
set -euo pipefail

if [[ "$#" -ne 4 ]]; then
  echo "write-deployed-yaml: expected 4 args (OUT POOL TRIGGER RECEIVER), got $#" >&2
  exit 1
fi
command -v cast >/dev/null 2>&1 || { echo "write-deployed-yaml: missing required command: cast" >&2; exit 1; }

out="$1"; shift
labels=(l2OraclePool l2SyncTrigger l2CreReceiver)
addrs=("$@")

declare -a checksummed
for i in "${!addrs[@]}"; do
  a="${addrs[$i]}"
  if [[ ! "$a" =~ ^0x[0-9a-fA-F]{40}$ || "$a" == 0x0000000000000000000000000000000000000000 ]]; then
    echo "write-deployed-yaml: ${labels[$i]} is not a valid non-zero address: '${a:-<unset>}'" >&2
    exit 1
  fi
  checksummed[$i]="$(cast to-check-sum-address "$a")"
done

# Stamp the deploy commit as a COMMENT — state-mate's .deployed loader accepts only the `deployed:`
# section, so a real key would be rejected. `just diffyscan-config` greps this stamp to pin the
# GitHub tree the explorer-published sources are diffed against. If the sources that land in the
# deployed contracts are dirty at deploy time the pinned commit won't match what was deployed, so
# stamp a "-dirty" suffix and let config generation refuse it. Scope the check to what actually
# affects the deployed sources — src/, lib/, and the build config — so unrelated dirt (.env, docs,
# the canary state-mate overlay) doesn't force a needless refusal. Use `git status --porcelain`
# (not `git diff`, which misses UNTRACKED source), with `:/`-anchored pathspecs so the check is
# correct from any caller working directory.
deploy_commit="$(git rev-parse HEAD)"
if [[ -n "$(git status --porcelain -- :/src :/lib :/foundry.toml :/remappings.txt)" ]]; then
  echo "write-deployed-yaml: WARNING — source tree dirty at deploy (src/lib/build config); stamping deploy-commit '-dirty' (diffyscan-config will refuse it)" >&2
  deploy_commit="${deploy_commit}-dirty"
fi

{
  echo "---"
  echo "# GENERATED by '${DEPLOYED_YAML_GENERATOR:-just deploy-test}' — review and commit alongside the migration; do not hand-edit."
  echo "# The three Stage-1 deploy outputs (OraclePool, SyncTrigger, CREReceiver) — the only contracts this"
  echo "# migration deploys. The pre-existing CustomSender proxy/impl + ProxyAdmin are external facts in"
  echo "# config/state/l2-<net>.inputs.yaml (externals:), NOT here. state-mate concatenates this file"
  echo "# (anchors first) ahead of the wiring <net>.yaml so the *aliases resolve."
  echo "# deploy-commit: $deploy_commit"
  echo "deployed:"
  echo "  l1: [] # L2 configs check no L1 contracts (the L1 receiver is verified by l1.yaml)."
  echo "  l2:"
  for i in "${!labels[@]}"; do
    printf '    - &%s "%s"\n' "${labels[$i]}" "${checksummed[$i]}"
  done
} > "$out"

echo "Wrote $out"
